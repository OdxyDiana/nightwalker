document.addEventListener("DOMContentLoaded", () => {
  if ("content" in document.createElement("template")) {
    let forum = document.querySelector("main");

    let templateForum = forum.querySelector("#forum-template");

    if (templateForum) {
      forumContent.reverse().forEach((category) => {
        templateForum.content.querySelector(".category-title h2").textContent =
          category.category;
        let clone = document.importNode(templateForum.content, true);
        let forumContainer = clone.querySelector(".forum-container");

        category.forums.forEach((forum) => {
          let template = document.querySelector("#forum-section-template");
          template.content.querySelector(".forum-title a").textContent =
            forum.title;
          let cloneForum = document.importNode(template.content, true);
          let tempDiv = document.createElement("div");
          tempDiv.innerHTML = forum.desc;

          Array.from(tempDiv.childNodes)
            .reverse()
            .forEach((node) => {
              cloneForum.querySelector(".forum-info").prepend(node);
            });
          forumContainer.append(cloneForum);
        });

        forum.prepend(clone);
      });
    }
  }
});
